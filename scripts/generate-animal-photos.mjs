import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { createRequire } from "node:module";
const require = createRequire(import.meta.url);
const imageSize = require("next/dist/compiled/image-size");
const catalog = JSON.parse(readFileSync(new URL("./data/animal-photos.json", import.meta.url), "utf8"));
const animals = JSON.parse(readFileSync(new URL("./data/animals-v1.json", import.meta.url), "utf8")).animals;
if (new Set(catalog.map(p => p.animalId)).size !== animals.length || catalog.length !== animals.length) throw new Error("Incomplete photo catalog");
for (const photo of catalog) {
  if (!animals.some(a => a.id === photo.animalId && a.scientific === photo.scientific)) throw new Error("Photo taxon mismatch");
  if (!photo.sourceUrl.startsWith("https://commons.wikimedia.org/") || !photo.license || !photo.artist) throw new Error("Missing image attribution");
  if (photo.licenseUrl && !/^https?:\/\//.test(photo.licenseUrl)) throw new Error("Invalid license link");
  for (const image of [photo.small, photo.large]) {
    if (!/^\/animals\/[a-z0-9-]+\.(jpg|png|webp)$/.test(image.src)) throw new Error("Invalid image path");
    const path = new URL("../public" + image.src, import.meta.url);
    if (!existsSync(path)) throw new Error("Photo asset missing");
    const bytes = readFileSync(path), dimensions = imageSize(bytes);
    if (Math.min(dimensions.width, dimensions.height) < 40 || !["jpg", "png", "webp"].includes(dimensions.type)) throw new Error("Invalid photo dimensions/type");
    Object.assign(image, { width: dimensions.width, height: dimensions.height, bytes: bytes.length });
  }
}
writeFileSync(new URL("./data/animal-photos.json", import.meta.url), JSON.stringify(catalog, null, 2) + "\n");
const photos = Object.fromEntries(catalog.map(p => [p.animalId, { src: p.small.src, largeSrc: p.large.src }]));
writeFileSync(new URL("../lib/data/animal-photos.ts", import.meta.url),
  "// Generated by scripts/generate-animal-photos.mjs.\n" +
  'import type { ItemPhoto } from "../item-photo";\n' +
  `export const animalPhotos: Record<string, ItemPhoto> = ${JSON.stringify(photos)};\n` +
  `export const animalPhotoCredits = ${JSON.stringify(catalog)};\n`);
console.log(`Generated ${catalog.length} verified photo records.`);
