import { readFileSync, writeFileSync } from "node:fs";
const source = JSON.parse(readFileSync(new URL("./data/animals-v1.json", import.meta.url), "utf8"));
const n = source.animals.length;
if (new Set(source.animals.map(a => a.id)).size !== n || source.cladeSizes.length !== n) throw new Error("Invalid animal dataset");
for (let i = 0; i < n; i++) for (let j = 0; j < n; j++) {
  if (source.cladeSizes[i]?.length !== n || !Number.isInteger(source.cladeSizes[i][j]) || source.cladeSizes[i][j] !== source.cladeSizes[j][i] || (i === j ? source.cladeSizes[i][j] !== 0 : source.cladeSizes[i][j] < 2)) throw new Error("Invalid animal distances");
}
writeFileSync(new URL("../lib/data/animals.ts", import.meta.url),
  "// Generated by scripts/generate-animals.mjs; edit scripts/data/animals-v1.json.\n" +
  `export const ANIMAL_DATASET_VERSION = ${JSON.stringify(source.version)};\n` +
  `export const ANIMAL_SOURCE = ${JSON.stringify(source.source)};\n` +
  `export const animalRecords: { id: string; name: string; scientific: string; aliases: string[] }[] = ${JSON.stringify(source.animals)};\n` +
  `export const animalCladeSizes: number[][] = ${JSON.stringify(source.cladeSizes)};\n`);
console.log(`Generated ${n} animals with ${n * n} precomputed distances.`);
