import "dotenv/config";
import { randomUUID } from "node:crypto";
import assert from "node:assert/strict";
import { prisma } from "../lib/prisma";
import { createFeedback, readFeedback, reviewFeedback } from "../lib/feedback";
if(!new URL(process.env.DATABASE_URL||"").pathname.includes("test"))throw Error("Use a disposable test database");
const ids=["feedback-test-a","feedback-test-b","feedback-test-admin"], [a,b,admin]=ids;
const body=(title="پیشنهاد برای بازی")=>({requestId:randomUUID(),kind:"SUGGESTION" as const,title,body:"لطفاً راهنمای بیشتری برای بازیکن‌ها نمایش بدهید."});
async function main(){
 process.env.FEEDBACK_ADMIN_USER_IDS=admin;
 await prisma.user.deleteMany({where:{id:{in:ids}}});
 await prisma.user.createMany({data:ids.map(id=>({id,firstName:id,username:"hidden_"+id,showUsername:false}))});
 const input=body();
 const results=await Promise.all([createFeedback(a,input),createFeedback(a,input)]);
 assert.equal(results[0].feedback.id,results[1].feedback.id);
 assert.equal(await prisma.feedback.count({where:{userId:a}}),1);
 assert.equal((await createFeedback(a,{...input,requestId:randomUUID()})).duplicate,true);
 assert.equal((await readFeedback(b,"mine",1) as {items:unknown[]}).items.length,0);
 await assert.rejects(()=>readFeedback(b,"review",1),/FEEDBACK_FORBIDDEN/);
 await assert.rejects(()=>reviewFeedback(b,{id:results[0].feedback.id,status:"ACCEPTED",reply:"خودم تأیید می‌کنم"}),/FEEDBACK_FORBIDDEN/);
 console.log("PASS idempotency, duplicate content, ownership and admin access");
 const id=results[0].feedback.id;
 await Promise.all([reviewFeedback(admin,{id,status:"ACCEPTED",reply:"پیشنهاد مفیدی بود"}),reviewFeedback(admin,{id,status:"ACCEPTED",reply:"پیشنهاد مفیدی بود"})]);
 const accepted=(await readFeedback(a,"leaderboard",1) as {rows:{points:number;username:string|null;name:string}[]});
 assert.equal(accepted.rows.length,1);assert.equal(accepted.rows[0].points,10);assert.equal(accepted.rows[0].username,null);assert.equal(accepted.rows[0].name,a);
 const mine=await readFeedback(a,"mine",1);assert.equal((mine as {items:{reply:string}[]}).items[0].reply,"پیشنهاد مفیدی بود");
 await reviewFeedback(admin,{id,status:"IMPLEMENTED",reply:"انجام شد"});
 assert.equal((await readFeedback(a,"leaderboard",1) as typeof accepted).rows[0].points,10);
 await reviewFeedback(admin,{id,status:"REVIEWED",reply:"نیاز به بررسی دوباره دارد"});
 assert.equal((await readFeedback(a,"leaderboard",1) as typeof accepted).rows.length,0);
 const queue=await readFeedback(admin,"review",1,"REVIEWED");
 assert.ok(!JSON.stringify(queue).includes('hidden_'));
 console.log("PASS repeated approval, implementation, revocation, private replies and hidden usernames");
 const requests=Array.from({length:7},(_,i)=>createFeedback(b,body(`پیشنهاد متفاوت شماره ${i}`)));
 const settled=await Promise.allSettled(requests);
 assert.equal(settled.filter(x=>x.status==="fulfilled").length,5);
 assert.equal(await prisma.feedback.count({where:{userId:b}}),5);
 await assert.rejects(()=>reviewFeedback(admin,{id:"missing",status:"ACCEPTED",reply:"تأیید"}),/FEEDBACK_NOT_FOUND/);
 console.log("PASS concurrent posting limits and missing reviews");
}
main().finally(async()=>{await prisma.user.deleteMany({where:{id:{in:ids}}});await prisma.$disconnect();}).catch(e=>{console.error(e);process.exitCode=1;});
